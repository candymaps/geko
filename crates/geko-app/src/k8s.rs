//! `geko k8s render`: the Kubernetes manifests of the operator mode, from `geko.toml`
//! (docs/OPERATOR_MODE_PLAN.md, step 7). One deployment and one service per active module, each
//! serving only its own (`geko serve --module`), a cron job that builds only its part (`geko build
//! --module`), a volume of bundles and downloads that all of them share, and an Ingress that sends
//! each path to its module. The same function the operator runs to reconcile them (`manifests`),
//! and the source of the manifests in `deploy/`: they are generated, never edited. `install` is what
//! the operator itself needs in a cluster.

use geko_module_sdk::module::ModuleName;
use serde_json::{Map, Value, json};

use crate::config::{Config, ModuleDeploy};

pub struct Options {
    /// Where the image of a module is: the prefix followed by the name of the module.
    pub image_prefix: String,
    pub tag: String,
    /// One image for every module (the one of `make start-dev`, which has them all), instead of
    /// the prefix and the tag.
    pub image: Option<String>,
    /// Size of the volume of bundles and downloads, and how it is mounted: every module reads and
    /// writes it, from other nodes, so `ReadWriteMany`, unless the cluster has a single node.
    pub storage: String,
    pub storage_class: Option<String>,
    pub access_mode: String,
    /// The service that answers `/` (the dashboard), when it is not the first module's: the one of
    /// the operator, which knows every module.
    pub dashboard: Option<String>,
    /// The host name that the Ingress answers for; any when none.
    pub host: Option<String>,
}

/// The volume that every module shares at `/var/lib/geko`, as it does in the single mode.
const DATA_CLAIM: &str = "geko-data";
/// The config map with `geko.toml` and the `geko-<module>.toml` files, which the overlays generate.
pub const CONFIG_MAP: &str = "geko";
pub(crate) const PORT: u16 = 8080;
/// The deployment and the service of the operator, and the label that its resources carry.
pub const OPERATOR: &str = "geko-operator";
/// The paths that every module serves for itself, which the Ingress sends to the first one.
const COMMON_PATHS: [&str; 4] = ["/docs", "/openapi.yaml", "/v1/attribution", "/health"];

pub fn render(config: &Config, options: &Options) -> String {
    let header = "# Generated by `geko k8s render` from geko.toml: edit that and render again, never this file.\n\
                  # The config map `geko` (geko.toml and the geko-<module>.toml files) is not here: each overlay makes it.\n";
    documents(header, &manifests(config, options))
}

fn documents(header: &str, resources: &[Value]) -> String {
    let documents: Vec<String> = resources.iter().map(yaml).collect();
    format!("{header}{}", documents.join("---\n"))
}

/// What the configuration asks for in the cluster, which `render` writes and the operator applies.
pub fn manifests(config: &Config, options: &Options) -> Vec<Value> {
    let modules = config.active_modules();
    let mut resources = vec![volume_claim(options)];
    for (index, module) in modules.iter().enumerate() {
        let deploy = config.deploy.modules.get(module.as_str());
        resources.push(deployment(module, deploy, options));
        resources.push(service(module));
        resources.push(build(module, deploy, options, config.data.max_age_days, index));
    }
    if !modules.is_empty() {
        resources.push(ingress(&modules, options.dashboard.as_deref(), options.host.as_deref()));
    }
    resources
}

/// What the operator needs to run in a cluster, as manifests (`geko k8s install`): the account with
/// the permissions to manage what `manifests` makes, its deployment, and the service of the
/// dashboard that it serves.
pub fn install(options: &Options, operator_image: &str) -> String {
    let labels = json!({ "app.kubernetes.io/name": "geko", "app.kubernetes.io/component": "operator", "app.kubernetes.io/part-of": "geko" });
    let selector = json!({ "app.kubernetes.io/name": "geko", "app.kubernetes.io/component": "operator" });
    let mut args = vec!["operator".to_owned(), "--listen".into(), format!("0.0.0.0:{PORT}"), "--image-prefix".into(), options.image_prefix.clone()];
    args.extend(["--tag".into(), options.tag.clone(), "--storage".into(), options.storage.clone()]);
    args.extend(["--access-mode".into(), options.access_mode.clone()]);
    if let Some(class) = &options.storage_class {
        args.extend(["--storage-class".into(), class.clone()]);
    }
    if let Some(image) = &options.image {
        args.extend(["--image".into(), image.clone()]);
    }
    if let Some(host) = &options.host {
        args.extend(["--host".into(), host.clone()]);
    }
    let manage = ["get", "list", "watch", "create", "patch", "delete"];
    let resources = vec![
        json!({ "apiVersion": "v1", "kind": "ServiceAccount", "metadata": { "name": OPERATOR, "labels": labels } }),
        json!({
            "apiVersion": "rbac.authorization.k8s.io/v1",
            "kind": "Role",
            "metadata": { "name": OPERATOR, "labels": labels },
            "rules": [
                { "apiGroups": [""], "resources": ["configmaps"], "verbs": ["get", "list", "watch"] },
                { "apiGroups": [""], "resources": ["services"], "verbs": manage },
                // The pods of each module, to ask each of them for its own state (the replicas keep their own counters).
                { "apiGroups": [""], "resources": ["pods"], "verbs": ["get", "list"] },
                // The claim of the volume is created and never deleted: it holds the bundles.
                { "apiGroups": [""], "resources": ["persistentvolumeclaims"], "verbs": ["get", "list", "watch", "create", "patch"] },
                { "apiGroups": ["apps"], "resources": ["deployments"], "verbs": manage },
                { "apiGroups": ["batch"], "resources": ["cronjobs"], "verbs": manage },
                // The builds that it starts when what they build from changes.
                { "apiGroups": ["batch"], "resources": ["jobs"], "verbs": manage },
                { "apiGroups": ["networking.k8s.io"], "resources": ["ingresses"], "verbs": manage },
            ],
        }),
        json!({
            "apiVersion": "rbac.authorization.k8s.io/v1",
            "kind": "RoleBinding",
            "metadata": { "name": OPERATOR, "labels": labels },
            "roleRef": { "apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": OPERATOR },
            "subjects": [{ "kind": "ServiceAccount", "name": OPERATOR }],
        }),
        json!({
            "apiVersion": "apps/v1",
            "kind": "Deployment",
            "metadata": { "name": OPERATOR, "labels": labels },
            "spec": {
                "replicas": 1,
                "selector": { "matchLabels": selector },
                "template": {
                    "metadata": { "labels": labels },
                    "spec": {
                        "serviceAccountName": OPERATOR,
                        "containers": [{
                            "name": "geko",
                            "image": operator_image,
                            "args": args,
                            "ports": [{ "name": "http", "containerPort": PORT }],
                            // It reads the configuration of the dashboard (keys, listen) from the
                            // same config map that it watches, mounted as in every pod.
                            "volumeMounts": [{ "name": "config", "mountPath": "/etc/geko", "readOnly": true }],
                            "livenessProbe": { "httpGet": { "path": "/health", "port": "http" }, "periodSeconds": 10 },
                            "readinessProbe": { "httpGet": { "path": "/ready", "port": "http" }, "periodSeconds": 5 },
                        }],
                        "volumes": [{ "name": "config", "configMap": { "name": CONFIG_MAP } }],
                    },
                },
            },
        }),
        json!({
            "apiVersion": "v1",
            "kind": "Service",
            "metadata": { "name": OPERATOR, "labels": labels },
            "spec": { "selector": selector, "ports": [{ "name": "http", "port": 80, "targetPort": "http" }] },
        }),
    ];
    let header = "# Generated by `geko k8s install`: the operator of geko, which makes the rest from the config map `geko`.\n\
                  # The config map itself is not here: each overlay makes it.\n";
    documents(header, &resources)
}

fn labels(module: &str) -> Value {
    json!({ "app.kubernetes.io/name": "geko", "app.kubernetes.io/component": module, "app.kubernetes.io/part-of": "geko" })
}

fn selector(module: &str) -> Value {
    json!({ "app.kubernetes.io/name": "geko", "app.kubernetes.io/component": module })
}

fn volume_claim(options: &Options) -> Value {
    let mut spec = json!({ "accessModes": [options.access_mode], "resources": { "requests": { "storage": options.storage } } });
    if let Some(class) = &options.storage_class {
        spec["storageClassName"] = json!(class);
    }
    json!({
        "apiVersion": "v1",
        "kind": "PersistentVolumeClaim",
        "metadata": { "name": DATA_CLAIM, "labels": { "app.kubernetes.io/name": "geko", "app.kubernetes.io/part-of": "geko" } },
        "spec": spec,
    })
}

/// What the container asks for: the processor as a request alone (a limit only throttles it), the
/// memory as a request and a limit.
fn resources(cpu: Option<&str>, memory: Option<&str>) -> Option<Value> {
    let (mut requests, mut limits) = (Map::new(), Map::new());
    if let Some(cpu) = cpu {
        requests.insert("cpu".into(), json!(cpu));
    }
    if let Some(memory) = memory {
        requests.insert("memory".into(), json!(memory));
        limits.insert("memory".into(), json!(memory));
    }
    let mut resources = Map::new();
    if !requests.is_empty() {
        resources.insert("requests".into(), requests.into());
    }
    if !limits.is_empty() {
        resources.insert("limits".into(), limits.into());
    }
    (!resources.is_empty()).then(|| resources.into())
}

fn container(module: &str, args: &[&str], resources: Option<Value>, options: &Options) -> Value {
    let mut container = json!({
        "name": "geko",
        "image": options.image.clone().unwrap_or_else(|| format!("{}{module}:{}", options.image_prefix, options.tag)),
        "args": args,
        "volumeMounts": [
            { "name": "data", "mountPath": "/var/lib/geko" },
            { "name": "config", "mountPath": "/etc/geko", "readOnly": true },
        ],
    });
    if let Some(resources) = resources {
        container["resources"] = resources;
    }
    container
}

fn volumes() -> Value {
    json!([
        { "name": "data", "persistentVolumeClaim": { "claimName": DATA_CLAIM } },
        { "name": "config", "configMap": { "name": CONFIG_MAP } },
    ])
}

/// The pods that serve one module: ready only once they have loaded its part of the bundle.
fn deployment(module: &ModuleName, deploy: Option<&ModuleDeploy>, options: &Options) -> Value {
    let name = module.as_str();
    let listen = format!("0.0.0.0:{PORT}");
    let mut container = container(
        name,
        &["serve", "--module", name, "--listen", &listen],
        resources(deploy.and_then(|d| d.cpu.as_deref()), deploy.and_then(|d| d.memory.as_deref())),
        options,
    );
    container["ports"] = json!([{ "name": "http", "containerPort": PORT }]);
    // `/health` is alive from the start; `/ready` waits for the bundle.
    container["livenessProbe"] = json!({ "httpGet": { "path": "/health", "port": "http" }, "periodSeconds": 10, "failureThreshold": 6 });
    container["readinessProbe"] = json!({ "httpGet": { "path": "/ready", "port": "http" }, "periodSeconds": 5, "failureThreshold": 3 });
    json!({
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": { "name": format!("geko-{name}"), "labels": labels(name) },
        "spec": {
            "replicas": deploy.map_or(1, |d| d.replicas),
            "selector": { "matchLabels": selector(name) },
            "template": {
                "metadata": { "labels": labels(name) },
                "spec": { "containers": [container], "volumes": volumes() },
            },
        },
    })
}

fn service(module: &ModuleName) -> Value {
    let name = module.as_str();
    json!({
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": { "name": format!("geko-{name}"), "labels": labels(name) },
        "spec": { "selector": selector(name), "ports": [{ "name": "http", "port": 80, "targetPort": "http" }] },
    })
}

/// The cron job that builds the part of one module, with the resources of a build and not those of
/// serving. It runs every `[data] max_age_days`, an hour apart from the module before it: the
/// builds share the downloads in `raw/`, and two of them must not fetch the same file at once. To
/// build now: `kubectl create job --from=cronjob/geko-build-<module> <name>`.
fn build(module: &ModuleName, deploy: Option<&ModuleDeploy>, options: &Options, max_age_days: u64, index: usize) -> Value {
    let name = module.as_str();
    let container = container(
        name,
        &["build", "--module", name],
        resources(deploy.and_then(|d| d.build_cpu.as_deref()), deploy.and_then(|d| d.build_memory.as_deref())),
        options,
    );
    json!({
        "apiVersion": "batch/v1",
        "kind": "CronJob",
        "metadata": { "name": format!("geko-build-{name}"), "labels": labels(name) },
        "spec": {
            "schedule": schedule(max_age_days, index),
            "concurrencyPolicy": "Forbid",
            "successfulJobsHistoryLimit": 1,
            "failedJobsHistoryLimit": 3,
            "jobTemplate": { "spec": {
                "backoffLimit": 1,
                "template": {
                    "metadata": { "labels": labels(name) },
                    "spec": { "restartPolicy": "Never", "containers": [container], "volumes": volumes() },
                },
            } },
        },
    })
}

fn schedule(max_age_days: u64, index: usize) -> String {
    let hour = 3 + index % 20;
    match max_age_days {
        0 | 1 => format!("0 {hour} * * *"),
        2..=27 => format!("0 {hour} */{max_age_days} * *"),
        _ => format!("0 {hour} 1 * *"),
    }
}

/// Each module under its own name. What is not a module's goes to the first one, which serves it as
/// every process does, unless a `dashboard` answers `/`: then only what each module serves for
/// itself (`/docs`, `/v1/attribution`…) goes to the first, and the dashboard gets the rest.
fn ingress(modules: &[ModuleName], dashboard: Option<&str>, host: Option<&str>) -> Value {
    let backend = |service: &str| json!({ "service": { "name": service, "port": { "name": "http" } } });
    let module = |m: &ModuleName| backend(&format!("geko-{m}"));
    let first = &modules[0];
    let mut paths: Vec<Value> = modules.iter().map(|m| json!({ "path": format!("/{m}/"), "pathType": "Prefix", "backend": module(m) })).collect();
    match dashboard {
        Some(service) => {
            paths.extend(COMMON_PATHS.iter().map(|path| json!({ "path": path, "pathType": "Exact", "backend": module(first) })));
            paths.push(json!({ "path": "/", "pathType": "Prefix", "backend": backend(service) }));
        }
        None => paths.push(json!({ "path": "/", "pathType": "Prefix", "backend": module(first) })),
    }
    let mut rule = json!({ "http": { "paths": paths } });
    if let Some(host) = host {
        rule["host"] = json!(host);
    }
    json!({
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": { "name": "geko", "labels": { "app.kubernetes.io/name": "geko", "app.kubernetes.io/part-of": "geko" } },
        "spec": { "rules": [rule] },
    })
}

/// A resource as a YAML document: keys in order, strings in double quotes (always valid), no anchors.
fn yaml(value: &Value) -> String {
    let mut out = String::new();
    block(value, 0, &mut out);
    out
}

fn scalar(value: &Value) -> String {
    match value {
        Value::Object(_) => "{}".into(),
        Value::Array(_) => "[]".into(),
        other => other.to_string(),
    }
}

fn key(key: &str) -> String {
    let plain = !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || "_-./".contains(c));
    if plain { key.to_owned() } else { Value::from(key).to_string() }
}

fn is_block(value: &Value) -> bool {
    match value {
        Value::Object(map) => !map.is_empty(),
        Value::Array(items) => !items.is_empty(),
        _ => false,
    }
}

/// `value`, a map or a list, as lines indented `indent` spaces.
fn block(value: &Value, indent: usize, out: &mut String) {
    let pad = " ".repeat(indent);
    match value {
        Value::Object(map) => {
            for (k, v) in map {
                if is_block(v) {
                    out.push_str(&format!("{pad}{}:\n", key(k)));
                    block(v, indent + 2, out);
                } else {
                    out.push_str(&format!("{pad}{}: {}\n", key(k), scalar(v)));
                }
            }
        }
        Value::Array(items) => {
            for item in items {
                if is_block(item) {
                    // The first line of a map goes beside the dash.
                    let mut inner = String::new();
                    block(item, indent + 2, &mut inner);
                    out.push_str(&format!("{pad}- {}", &inner[indent + 2..]));
                } else {
                    out.push_str(&format!("{pad}- {}\n", scalar(item)));
                }
            }
        }
        other => out.push_str(&format!("{pad}{}\n", scalar(other))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn options() -> Options {
        Options {
            image_prefix: "ghcr.io/candymaps/geko-".into(),
            tag: "latest".into(),
            image: None,
            storage: "20Gi".into(),
            storage_class: None,
            access_mode: "ReadWriteMany".into(),
            dashboard: None,
            host: None,
        }
    }

    fn rendered(toml: &str) -> String {
        render(&Config::parse(toml).unwrap(), &options())
    }

    #[test]
    fn writes_maps_lists_and_scalars_as_yaml() {
        let value = json!({
            "a": { "b": [1, true, "x y"], "empty": {}, "none": [] },
            "list": [{ "name": "one", "ports": [{ "port": 80 }] }, "two"],
            "needs quotes": null,
        });
        assert_eq!(
            yaml(&value),
            "a:\n  b:\n    - 1\n    - true\n    - \"x y\"\n  empty: {}\n  none: []\nlist:\n  - name: \"one\"\n    ports:\n      - port: 80\n  - \"two\"\n\"needs quotes\": null\n"
        );
    }

    #[test]
    fn a_deployment_and_a_build_for_each_active_module() {
        let out = rendered("[modules]\ngeocoder = true\ntiles = true\n");
        for module in ["geocoder", "tiles"] {
            assert!(out.contains(&format!("name: \"geko-{module}\"\n")), "{module}");
            assert!(out.contains(&format!("name: \"geko-build-{module}\"\n")), "{module}");
            assert!(out.contains(&format!("image: \"ghcr.io/candymaps/geko-{module}:latest\"\n")), "{module}");
        }
        // One serves and one builds, each only its own module.
        assert_eq!(out.matches("- \"serve\"\n").count(), 2);
        assert_eq!(out.matches("- \"build\"\n").count(), 2);
        assert_eq!(out.matches("- \"--module\"\n").count(), 4);
        assert!(out.contains("kind: \"Ingress\""));
        assert!(out.contains("path: \"/tiles/\"") && out.contains("path: \"/geocoder/\""));
        assert!(out.contains("path: \"/ready\"") && out.contains("path: \"/health\""), "the probes");
        assert_eq!(out.matches("---\n").count(), out.matches("apiVersion:").count() - 1, "one document per resource");
    }

    #[test]
    fn a_disabled_module_has_no_resources() {
        let out = rendered("[modules]\ntiles = false\n");
        assert!(out.contains("geko-geocoder") && !out.contains("geko-tiles") && !out.contains("/tiles/"));
        let none = rendered("[modules]\ngeocoder = false\ntiles = false\n");
        assert!(!none.contains("Ingress") && none.contains("PersistentVolumeClaim"));
    }

    #[test]
    fn replicas_and_resources_come_from_deploy() {
        let out = rendered(
            "[deploy.geocoder]\nreplicas = 3\ncpu = \"500m\"\nmemory = \"4Gi\"\nbuild_memory = \"6Gi\"\n\n[deploy.tiles]\nreplicas = 1\n",
        );
        assert!(out.contains("replicas: 3\n") && out.contains("replicas: 1\n"));
        // The pods that serve ask for 4Gi, the job that builds for 6Gi, and tiles for nothing.
        assert!(out.contains("memory: \"4Gi\"") && out.contains("memory: \"6Gi\"") && out.contains("cpu: \"500m\""));
        assert_eq!(out.matches("resources:\n").count(), 2 + 1, "serving and building of the geocoder, and the claim");
    }

    #[test]
    fn builds_are_an_hour_apart_and_follow_max_age_days() {
        assert_eq!(schedule(30, 0), "0 3 1 * *");
        assert_eq!(schedule(7, 1), "0 4 */7 * *");
        assert_eq!(schedule(1, 2), "0 5 * * *");
        let out = rendered("[data]\nmax_age_days = 7\n");
        assert!(out.contains("schedule: \"0 3 */7 * *\"") && out.contains("schedule: \"0 4 */7 * *\""));
    }

    #[test]
    fn one_image_serves_for_every_module() {
        let config = Config::parse("").unwrap();
        let out = render(&config, &Options { image: Some("geko:dev".into()), ..options() });
        assert_eq!(out.matches("image: \"geko:dev\"\n").count(), 4, "two to serve and two to build");
        assert!(!out.contains("ghcr.io"));
    }

    #[test]
    fn the_dashboard_answers_the_root_and_the_first_module_what_is_common() {
        let config = Config::parse("[modules]\ngeocoder = true\ntiles = true\n").unwrap();
        let plain = render(&config, &options());
        assert!(!plain.contains("geko-operator") && !plain.contains("Exact"), "by default the first module answers the root");
        let out = render(&config, &Options { dashboard: Some("geko-operator".into()), ..options() });
        let paths = ingress(&config.active_modules(), Some("geko-operator"), None);
        let rules = paths["spec"]["rules"][0]["http"]["paths"].as_array().unwrap();
        let backend = |path: &str| rules.iter().find(|r| r["path"] == path).map(|r| r["backend"]["service"]["name"].clone());
        assert_eq!(backend("/"), Some(json!("geko-operator")));
        for path in COMMON_PATHS {
            assert_eq!(backend(path), Some(json!("geko-geocoder")), "{path}");
        }
        assert_eq!(backend("/tiles/"), Some(json!("geko-tiles")));
        assert!(out.contains("pathType: \"Exact\""));
    }

    #[test]
    fn the_operator_installs_with_the_permissions_it_needs_and_none_to_delete_the_volume() {
        let out = install(&Options { storage_class: Some("nfs".into()), ..options() }, "ghcr.io/candymaps/geko:latest");
        for kind in ["ServiceAccount", "Role", "RoleBinding", "Deployment", "Service"] {
            assert!(out.contains(&format!("kind: \"{kind}\"\n")), "{kind}");
        }
        assert!(out.contains("image: \"ghcr.io/candymaps/geko:latest\"\n") && out.contains("serviceAccountName: \"geko-operator\"\n"));
        assert!(out.contains("- \"--storage-class\"\n") && out.contains("- \"nfs\"\n"));
        let role = out.split("---\n").find(|d| d.contains("kind: \"Role\"")).unwrap();
        let claims = role.split("- apiGroups:").find(|r| r.contains("persistentvolumeclaims")).unwrap();
        assert!(!claims.contains("\"delete\""), "{claims}");
        assert_eq!(out.matches("---\n").count(), out.matches("apiVersion:").count() - 1, "one document per resource");
    }

    #[test]
    fn the_volume_is_shared_and_may_name_its_class() {
        let out = render(&Config::parse("").unwrap(), &Options { storage_class: Some("nfs".into()), ..options() });
        assert!(out.contains("- \"ReadWriteMany\"") && out.contains("storage: \"20Gi\"") && out.contains("storageClassName: \"nfs\""));
        assert!(!rendered("").contains("storageClassName"));
    }
}
